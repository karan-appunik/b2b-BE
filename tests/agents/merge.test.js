const ROOT = require("path").join(__dirname, "..", "..");
process.chdir(ROOT);
process.env.AGENT_MFA_DEFAULT = "false";
process.env.INTERNAL_API_KEY = "k";
process.env.JWT_SECRET = "s";
const R = (m) => require(require("path").join(ROOT, m));
const mongoose = R("node_modules/mongoose");
const jwt = R("node_modules/jsonwebtoken");
const app = R("app");
const User = R("src/models/user.model");
const Customer = R("src/models/customer.model");
const Ctx = R("src/models/contextSession.model");
const Quote = R("src/models/quote.model");
const Override = R("src/models/overrideRequest.model");
const AgentCart = R("src/models/agentCart.model");
const AgentPin = R("src/models/agentPin.model");
const ShoppingList = R("src/models/shoppingList.model");
const PaymentLink = R("src/models/paymentLink.model");
const Grant = R("src/models/agentScopeGrant.model");
const Notification = R("src/models/notification.model");
const Audit = R("src/models/auditEvent.model");
let pass = 0, fail = 0;
const ok = (n, c, extra) => { c ? pass++ : fail++; console.log((c ? "PASS " : "FAIL ") + n + (c ? "" : "  " + JSON.stringify(extra))); };
(async () => {
  await mongoose.connect("mongodb://localhost:27017/sparklayer_test_merge");
  await mongoose.connection.dropDatabase();
  const srv = app.listen(0);
  const base = "http://localhost:" + srv.address().port;
  const shop = "t.myshopify.com";
  const user = await User.create({ name: "M", email: "m@x.com", password: "x", shop });
  const AH = { Authorization: "Bearer " + jwt.sign({ id: user._id }, "s"), "Content-Type": "application/json" };
  const adm = async (m, p, body) => { const r = await fetch(base + p, { method: m, headers: AH, body: body ? JSON.stringify(body) : undefined }); return { s: r.status, j: await r.json().catch(() => null) }; };
  await adm("GET", "/api/roles");
  const gid = (n) => "gid://shopify/Customer/" + n;
  const mk = (n, extra) => Customer.create({ name: n, email: n + "@x.com", shop, shopifyCustomerId: gid(n), ...extra });
  const a1 = await mk("a1", { role: "sales_agent" });
  const a2 = await mk("a2", { role: "sales_agent" });
  const oldC = await mk("oldco", { company: "Old Co", internalNotes: "likes calls" });
  const newC = await mk("newco", { company: "New Co", internalNotes: "VIP" });
  const susp = await mk("susp", { accountStatus: "suspended" });

  await Ctx.create({ shop, agent: a1._id, customer: oldC._id, issuedAt: new Date(), expiresAt: new Date(Date.now() + 3600e3) });
  await Quote.create({ shop, number: "Q-1", customer: oldC._id, ownerAgent: a1._id, status: "SENT" });
  await Quote.create({ shop, number: "Q-2", customer: oldC._id, ownerAgent: a1._id, status: "CONVERTED" });
  await Override.create({ shop, agent: a2._id, customer: oldC._id, type: "UNIT_PRICE", permission: "price.override", baseline: { amount: 100, currency: "USD" }, proposed: { amount: 70, currency: "USD" }, reasonCode: "OTHER", reasonText: "x", status: "PENDING_APPROVAL" });
  await AgentCart.create({ shop, agent: a1._id, customer: oldC._id, items: [{ variantId: "1", quantity: 1 }] });
  await AgentPin.create({ shop, agent: a1._id, customer: oldC._id });
  await AgentPin.create({ shop, agent: a2._id, customer: oldC._id });
  await AgentPin.create({ shop, agent: a2._id, customer: newC._id });
  await ShoppingList.create({ shop, customer: oldC._id, name: "Weekly", createdBy: a1._id, items: [{ variantId: "1", quantity: 2 }] });
  await PaymentLink.create({ shop, token: "t1", customer: oldC._id, agent: a1._id, draftOrderId: "d1", invoiceUrl: "https://x/1", amount: 5000, currency: "USD", expiresAt: new Date(Date.now() + 3600e3) });
  await Grant.create({ shop, agent: a1._id, scopeType: "customer", scopeId: String(oldC._id) });
  await Grant.create({ shop, agent: a2._id, scopeType: "customer", scopeId: String(oldC._id) });
  await Grant.create({ shop, agent: a2._id, scopeType: "customer", scopeId: String(newC._id) });

  let r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(oldC._id) });
  ok("merging into itself is refused", r.s === 400 && r.j.code === "SAME_CUSTOMER", r);
  r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(susp._id) });
  ok("merging into an account that is not active is refused", r.s === 400 && r.j.code === "TARGET_NOT_ACTIVE", r);
  r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(a1._id) });
  ok("an agent account can not be merged", r.s === 400 && r.j.code === "AGENT_ACCOUNT", r);
  r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(new mongoose.Types.ObjectId()) });
  ok("an unknown account is a 404", r.s === 404, r);

  r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(newC._id) });
  ok("the merge works and says what happened", r.s === 200 && r.j.quotesWithdrawn === 1 && r.j.exceptionsCancelled === 1 && r.j.cartsClosed === 1 && r.j.paymentLinksWithdrawn === 1 && r.j.listsMoved === 1, r.j);
  const old = await Customer.findById(oldC._id);
  ok("the old account is merged and points to the new one", old.accountStatus === "merged" && String(old.mergedInto) === String(newC._id), old);
  ok("anyone ordering for it is taken out", !!(await Ctx.findOne({ customer: oldC._id })).revokedAt);
  ok("an open quote is withdrawn with the reason; a converted one is left", (await Quote.findOne({ number: "Q-1" })).status === "WITHDRAWN" && /Make a new quote/.test((await Quote.findOne({ number: "Q-1" })).activity.slice(-1)[0].comment) && (await Quote.findOne({ number: "Q-2" })).status === "CONVERTED");
  ok("the waiting exception is cancelled", (await Override.findOne({ customer: oldC._id })).status === "CANCELLED");
  ok("the cart is closed, not moved to another customer", (await AgentCart.countDocuments({ customer: oldC._id })) === 0 && (await AgentCart.countDocuments({ customer: newC._id })) === 0);
  ok("the payment link is withdrawn", (await PaymentLink.findOne({ token: "t1" })).status === "REVOKED");
  ok("the saved list follows", (await ShoppingList.countDocuments({ customer: newC._id })) === 1 && (await ShoppingList.countDocuments({ customer: oldC._id })) === 0);
  ok("pins follow, without doubling up", (await AgentPin.countDocuments({ customer: newC._id })) === 2 && (await AgentPin.countDocuments({ customer: oldC._id })) === 0 && r.j.pinsMoved === 1, r.j);
  ok("agents who could act for the old account can for the new one, once", (await Grant.countDocuments({ scopeType: "customer", scopeId: String(newC._id) })) === 2 && r.j.accessCopied === 1, r.j);
  ok("the notes are kept with the account that stays", /VIP/.test((await Customer.findById(newC._id)).internalNotes) && /From oldco: likes calls/.test((await Customer.findById(newC._id)).internalNotes));
  const notes = await Notification.find({ type: "customer.merged" }).lean();
  ok("each agent who had work is told what was closed", notes.length === 2 && notes.some((n) => String(n.recipient) === String(a1._id) && /quote/.test(n.body) && /New Co/.test(n.title)) && notes.some((n) => String(n.recipient) === String(a2._id) && /exception/.test(n.body)), notes);
  ok("the merge is audited", !!(await Audit.findOne({ shop, action: "customer.merged", "metadata.mergedInto": String(newC._id) })));
  r = await adm("POST", `/api/customers/${oldC._id}/merge`, { intoCustomerId: String(newC._id) });
  ok("doing it twice is refused", r.s === 400 && r.j.code === "ALREADY_MERGED", r);

  console.log(`\n${pass} passed, ${fail} failed`);
  await mongoose.connection.dropDatabase();
  process.exit(fail ? 1 : 0);
})();
