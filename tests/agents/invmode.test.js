const ROOT = require("path").join(__dirname, "..", "..");
process.chdir(ROOT);
process.env.INTERNAL_API_KEY = "k";
process.env.JWT_SECRET = "s";
const R = (m) => require(require("path").join(ROOT, m));
const mongoose = R("node_modules/mongoose");
const jwt = R("node_modules/jsonwebtoken");
const app = R("app");
const User = R("src/models/user.model");
let pass = 0, fail = 0;
const ok = (n, c, extra) => { c ? pass++ : fail++; console.log((c ? "PASS " : "FAIL ") + n + (c ? "" : "  " + JSON.stringify(extra))); };
(async () => {
  await mongoose.connect("mongodb://localhost:27017/sparklayer_test_invmode");
  await mongoose.connection.dropDatabase();
  const srv = app.listen(0);
  const base = "http://localhost:" + srv.address().port;
  const shop = "t.myshopify.com";
  const user = await User.create({ name: "Merchant", email: "m@x.com", password: "x", shop });
  const AH = { Authorization: "Bearer " + jwt.sign({ id: user._id }, "s"), "Content-Type": "application/json" };
  const IH = { "x-internal-api-key": "k" };
  const get = async () => (await fetch(base + "/api/internal/agent/module-settings?shop=" + shop, { headers: IH })).json();
  let j = await get();
  ok("default is only check stock", j.inventoryMode === "informational" && j.paymentLinkValidHours === 72, j);
  let r = await fetch(base + "/api/agent-settings", { method: "PUT", headers: AH, body: JSON.stringify({ inventoryMode: "reserve_orders" }) });
  ok("merchant can switch to reserve", r.status === 200, r.status);
  j = await get();
  ok("storefront sees reserve", j.inventoryMode === "reserve_orders", j);
  r = await fetch(base + "/api/agent-settings", { method: "PUT", headers: AH, body: JSON.stringify({ inventoryMode: "bogus" }) });
  ok("bad value refused", r.status === 400, r.status);
  j = await get();
  ok("still reserve after bad value", j.inventoryMode === "reserve_orders", j);
  // ---- substitutes
  const put = (body) => fetch(base + "/api/agent-settings", { method: "PUT", headers: AH, body: JSON.stringify(body) }).then(async (x) => ({ s: x.status, j: await x.json().catch(() => null) }));
  r = await put({ substitutes: [{ fromSku: "A-1", toSku: "A-2", note: "Same style" }, { fromSku: "B-1", toSku: "B-2" }] });
  ok("substitutes save", r.s === 200 && r.j.substitutes.length === 2, r);
  j = await get();
  ok("the storefront gets them", j.substitutes.length === 2 && j.substitutes[0].fromSku === "A-1" && j.substitutes[0].toSku === "A-2" && j.substitutes[0].note === "Same style" && j.substitutes[1].note === null, j);
  r = await put({ substitutes: [{ fromSku: "A-1", toSku: "a-1" }] });
  ok("an item can not replace itself", r.s === 400, r);
  r = await put({ substitutes: [{ fromSku: "A-1", toSku: "A-2" }, { fromSku: "a-1", toSku: "A-3" }] });
  ok("one substitute per item", r.s === 400, r);
  r = await put({ substitutes: [{ fromSku: "", toSku: "A-2" }] });
  ok("both SKUs are needed", r.s === 400, r);
  j = await get();
  ok("a refused change leaves the earlier list", j.substitutes.length === 2, j);
  r = await put({ substitutes: [] });
  ok("the list can be emptied", r.s === 200 && (await get()).substitutes.length === 0, r);

  console.log(`\n${pass} passed, ${fail} failed`);
  await mongoose.connection.dropDatabase();
  srv.close(); await mongoose.disconnect();
  process.exit(fail ? 1 : 0);
})();
